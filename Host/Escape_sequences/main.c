#include <stdio.h>

int main()
{
    printf("Single quote: \'\n");
    printf("Double quote: \"\n");
    printf("Backslash: \\\n");
    printf("Null character: \0 \n");
    printf("\nBell: \a\n");
    printf("Backspace: ABC\bDSD\n");
    printf("Form feed: ABC\fDEF\n");
    printf("Newline: Hello\nWorld\n");
    printf("Carriage return: ABC\rXYZ\n");
    printf("Horizontal tab: Hello\tWorld\n");
    printf("Vertical tab: Hello\v\vWorld\n");

    return 0;
}
